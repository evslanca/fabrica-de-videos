//! Multi-Agent Orchestrator ("Cérebro Inteligente") for the AI Video Factory.
//!
//! Coordinates specialized AI agents (robots) with distinct names, roles,
//! editable system prompts, smart pipeline ordering, and full CRUD management.

use std::path::Path;

use serde::{Deserialize, Serialize};

use crate::presets::{EditingStyle, FactoryProConfig, PlatformPreset};

/// Type of creative production orchestrated by the multi-agent brain.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum ProductionType {
    #[default]
    VideoYoutube,
    ReelsShorts,
    FilmeCurta,
    PropagandaComercial,
    JingleAudio,
    DublagemClonagem,
    AvatarApresentador,
}

/// Role, identity, and editable command prompt of a specialized robot in the Factory.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentProfile {
    /// Unique identifier (e.g. "aria", "kael", "lyra", "nova", "kronos").
    pub id: String,
    /// Robot's display name.
    pub name: String,
    /// Short role title.
    pub role: String,
    /// Editable system/command prompt that guides this robot's behavior.
    pub system_prompt: String,
    /// Specific responsibilities in the pipeline.
    pub responsibilities: Vec<String>,
    /// Target factory node ID owned by this robot.
    pub target_node: String,
    /// Execution priority (lower runs earlier).
    pub priority: u32,
    /// Whether this robot is active in the pipeline.
    pub enabled: bool,
}

/// A single step assigned to a robot in the orchestrated production plan.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OrchestratorTask {
    /// Name of the assigned robot.
    pub agent_name: String,
    /// Robot's role.
    pub agent_role: String,
    /// Actionable instruction for this stage.
    pub action: String,
    /// Target node in the Factory DAG.
    pub target_node: String,
}

/// Complete multi-agent production plan generated by the Orchestrator.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OrchestratorPlan {
    pub goal: String,
    pub production_type: ProductionType,
    pub team: Vec<AgentProfile>,
    pub tasks: Vec<OrchestratorTask>,
    pub recommended_pro: FactoryProConfig,
}

/// Full CRUD + Smart Organization registry for Factory robots.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentRegistry {
    pub agents: Vec<AgentProfile>,
}

impl Default for AgentRegistry {
    fn default() -> Self {
        Self {
            agents: default_agent_team(),
        }
    }
}

impl AgentRegistry {
    /// Loads the registry from a JSON file, falling back to [`default_agent_team`].
    pub fn load_or_default(path: &Path) -> Self {
        std::fs::read_to_string(path)
            .ok()
            .and_then(|s| serde_json::from_str(&s).ok())
            .unwrap_or_default()
    }

    /// Persists the registry to a JSON file.
    pub fn save(&self, path: &Path) -> std::io::Result<()> {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let json = serde_json::to_string_pretty(self)
            .map_err(|e| std::io::Error::new(std::io::ErrorKind::Other, e))?;
        std::fs::write(path, json)
    }

    /// Creates a new robot (replaces if `id` already exists).
    pub fn create(&mut self, profile: AgentProfile) {
        self.agents.retain(|a| a.id != profile.id);
        self.agents.push(profile);
    }

    /// Reads a robot by `id`.
    pub fn get(&self, id: &str) -> Option<&AgentProfile> {
        self.agents.iter().find(|a| a.id == id)
    }

    /// Updates a robot's name, role, system prompt, target node, priority, or enabled state.
    pub fn update(
        &mut self,
        id: &str,
        name: Option<String>,
        role: Option<String>,
        system_prompt: Option<String>,
        target_node: Option<String>,
        priority: Option<u32>,
        enabled: Option<bool>,
    ) -> bool {
        let Some(agent) = self.agents.iter_mut().find(|a| a.id == id) else {
            return false;
        };
        if let Some(v) = name {
            agent.name = v;
        }
        if let Some(v) = role {
            agent.role = v;
        }
        if let Some(v) = system_prompt {
            agent.system_prompt = v;
        }
        if let Some(v) = target_node {
            agent.target_node = v;
        }
        if let Some(v) = priority {
            agent.priority = v;
        }
        if let Some(v) = enabled {
            agent.enabled = v;
        }
        true
    }

    /// Deletes a robot by `id`.
    pub fn delete(&mut self, id: &str) -> bool {
        let before = self.agents.len();
        self.agents.retain(|a| a.id != id);
        self.agents.len() < before
    }

    /// Smartly organizes robots by pipeline stage (`script` -> `voice` -> `media`/`avatar` -> `music`/`sfx` -> `caption` -> `export`) and priority.
    pub fn organize_smart(&mut self) {
        fn stage_rank(node: &str) -> u32 {
            match node {
                "script" => 10,
                "voice" => 20,
                "media" => 30,
                "avatar" => 35,
                "music" => 40,
                "sfx" => 50,
                "caption" => 60,
                "export" => 70,
                _ => 80,
            }
        }
        self.agents
            .sort_by_key(|a| (if a.enabled { 0 } else { 1 }, stage_rank(&a.target_node), a.priority));
        for (idx, agent) in self.agents.iter_mut().enumerate() {
            agent.priority = (idx as u32 + 1) * 10;
        }
    }
}

