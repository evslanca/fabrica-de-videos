/// Builds an intelligent multi-agent [`OrchestratorPlan`] from a user goal and production type.
pub fn build_plan(goal: &str, production_type: ProductionType) -> OrchestratorPlan {
    let mut registry = AgentRegistry::default();
    registry.organize_smart();
    let team: Vec<AgentProfile> = registry.agents.into_iter().filter(|a| a.enabled).collect();
    let mut pro = FactoryProConfig::default();

    match production_type {
        ProductionType::VideoYoutube => pro.apply_platform_preset(PlatformPreset::Youtube16x9),
        ProductionType::ReelsShorts => pro.apply_platform_preset(PlatformPreset::InstagramReels),
        ProductionType::FilmeCurta => {
            pro.apply_platform_preset(PlatformPreset::Youtube16x9);
            pro.editing_style = EditingStyle::IlustrativaPip;
        }
        ProductionType::PropagandaComercial => {
            pro.apply_platform_preset(PlatformPreset::InstagramReels);
            pro.editing_style = EditingStyle::ZoomDinamico;
        }
        ProductionType::JingleAudio => {
            pro.apply_platform_preset(PlatformPreset::FacebookFeed);
        }
        ProductionType::DublagemClonagem => {
            pro.apply_platform_preset(PlatformPreset::Youtube16x9);
            pro.auto_ducking = true;
        }
        ProductionType::AvatarApresentador => {
            pro.apply_platform_preset(PlatformPreset::Youtube16x9);
            pro.editing_style = EditingStyle::LadoALado;
        }
    }

    let tasks = team
        .iter()
        .map(|agent| OrchestratorTask {
            agent_name: agent.name.clone(),
            agent_role: agent.role.clone(),
            action: format!("[{}] ({}) -> {}", agent.name, agent.system_prompt, goal),
            target_node: agent.target_node.clone(),
        })
        .collect();

    OrchestratorPlan {
        goal: goal.to_string(),
        production_type,
        team,
        tasks,
        recommended_pro: pro,
    }
}
